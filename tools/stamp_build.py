"""Stamp the installed build into the addon and report whether its terms are baked.

Panorama has no build API and cannot read `steam.inf` (no file access, and
`AsyncWebRequest` was removed in 6864), so the one place the installed build can
be read is the installer, which is already reading the game folder. This writes
that build into `panorama/scripts/soul_lens_build.js`; the strip compares it with
the bake and with the per-build terms archive (`tools/terms_archive.py`) and
withholds the weapon terms when the matching snapshot is absent.

usage:
  python tools/stamp_build.py
  python tools/stamp_build.py --steam-inf D:/SteamLibrary/steamapps/common/Deadlock/game/citadel/steam.inf
  python tools/stamp_build.py --build 6864 --status-only
"""

from __future__ import annotations

import argparse
import pathlib
import sys

try:  # script form and package import both work
    import terms_archive
except ImportError:  # pragma: no cover - the package path
    from tools import terms_archive

STEAM_INF = pathlib.Path("D:/SteamLibrary/steamapps/common/Deadlock/game/citadel/steam.inf")
OUT = pathlib.Path("panorama/scripts/soul_lens_build.js")


def installed_build(steam_inf: pathlib.Path) -> str:
    if not steam_inf.exists():
        return ""
    for line in steam_inf.read_text(encoding="utf-8", errors="replace").splitlines():
        key, _, value = line.partition("=")
        if key.strip() == "ClientVersion":
            return value.strip()
    return ""


def write_stamp(build: str, out: pathlib.Path = OUT) -> pathlib.Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "// generated by tools/stamp_build.py; do not hand-edit\n"
        f'var SoulLensLiveBuild = "{build}";\n'
        "try { if (typeof window !== 'undefined') window.SoulLensLiveBuild = SoulLensLiveBuild; } catch (e) {}\n",
        encoding="utf-8",
    )
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--steam-inf", default=str(STEAM_INF))
    parser.add_argument("--build", default="", help="override the build (tests and stale witnesses only)")
    parser.add_argument("--out", default=str(OUT))
    parser.add_argument("--archive", default=str(terms_archive.ARCHIVE))
    parser.add_argument("--status-only", action="store_true")
    args = parser.parse_args()

    build = args.build or installed_build(pathlib.Path(args.steam_inf))
    if not build:
        print(f"REFUSED: no ClientVersion in {args.steam_inf} and no --build", file=sys.stderr)
        return 1
    if not args.status_only:
        path = write_stamp(build, pathlib.Path(args.out))
        print(f"stamped installed build {build} into {path}")
    row = terms_archive.status(build, pathlib.Path(args.archive))
    if row["state"] == "read":
        print(f"terms for build {build}: baked ({row['items']} items, {row['digest']})")
        return 0
    print(f"terms for build {build}: MISSING — the strip will withhold weapon terms. "
          f"Run python tools/ingest.py once the API serves {build}.", file=sys.stderr)
    return 3


if __name__ == "__main__":
    raise SystemExit(main())
